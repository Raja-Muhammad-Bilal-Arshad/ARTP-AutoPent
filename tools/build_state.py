#!/usr/bin/env python3
# tools/build_state.py
# Aggregates individual tool outputs (recon, crawl, exploit) into a single state JSON file.

import argparse
import json
import os
import time

def load_json_safe(path):
    if not os.path.exists(path):
        return {}
    try:
        with open(path, 'r') as f:
            return json.load(f)
    except Exception as e:
        # It's okay if some optional files are missing, just return empty
        return {}

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--dir", required=True, help="Directory containing tool outputs (e.g., tmp_orch)")
    parser.add_argument("--out", required=True, help="Output state JSON file (e.g., state_from_live.json)")
    args = parser.parse_args()

    # Map internal keys to filenames generated by the tools
    files_map = {
        "recon": "recon_service.json",
        "probe": "dir_probe.json",
        "crawl": "crawl.json",
        "creds": "check_creds.json",
        "exploit": "exploit_sim.json",
        "post": "post_exploit.json"
    }

    data = {}
    for key, filename in files_map.items():
        path = os.path.join(args.dir, filename)
        data[key] = load_json_safe(path)

    # Construct the unified state object required by the harness
    state = {
        "meta": {
            "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "source": "auto_run_orchestrator"
        },
        "hosts": [],
        "services": [],
        # Raw data blocks
        "recon_data": data["recon"],
        "crawl_data": data["crawl"],
        "probe_data": data["probe"],
        # Actionable results
        "credentials": data["creds"].get("results", []),
        "exploits_attempted": data["exploit"].get("attempts", []),
        "post_exploitation": data["post"].get("post", []),
        # Flag to indicate this state is fully populated
        "ready": True
    }

    # Normalize host info if available from recon
    recon = data["recon"]
    if recon.get("host"):
        state["hosts"].append({
            "host": recon.get("host"),
            "ip": recon.get("host"), # simplified
            "ports": [recon.get("port")] if recon.get("port") else []
        })
    
    if recon.get("port"):
        state["services"].append({
            "host": recon.get("host"),
            "port": recon.get("port"),
            "protocol": "tcp",
            "banner": recon.get("tcp_banner", "")
        })

    # Save to output
    with open(args.out, "w") as f:
        json.dump(state, f, indent=2)
    
    print(f"[+] Successfully built unified state file: {args.out}")

if __name__ == "__main__":
    main()
